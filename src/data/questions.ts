// Helper functions for question filtering and selection
export function getFilteredQuestions(options: {
  gameMode?: GameMode;
  categories?: QuestionCategory[];
  intensity?: IntensityLevel;
  excludeSpicy?: boolean;
}): Question[] {
  return SEED_QUESTIONS.filter((q) => {
    // Mode match
    if (options.gameMode && !q.suitableModes.includes(options.gameMode)) {
      return false;
    }
    // Category match
    if (
      options.categories &&
      options.categories.length > 0 &&
      !options.categories.includes(q.category)
    ) {
      return false;
    }
    // Intensity match
    if (options.intensity) {
      if (options.intensity === "mild" && q.intensity !== "mild") return false;
      if (options.intensity === "medium" && q.intensity === "spicy") return false;
    }
    if (options.excludeSpicy && (q.category === "Spicy" || q.intensity === "spicy")) {
      return false;
    }
    return true;
  });
}

export function formatQuestionText(text: string, targetPlayerName?: string): string {
  if (!targetPlayerName) {
    return text.replace(/\{target\}'s/g, "their").replace(/\{target\}/g, "they");
  }
  return text.replace(/\{target\}'s/g, `${targetPlayerName}'s`).replace(/\{target\}/g, targetPlayerName);
}

export function pickRandomQuestions(
  count: number,
  options: {
    gameMode?: GameMode;
    categories?: QuestionCategory[];
    intensity?: IntensityLevel;
    excludeSpicy?: boolean;
  },
  usedIds: Set<string> = new Set()
): Question[] {
  let pool = getFilteredQuestions(options).filter((q) => !usedIds.has(q.id));
  if (pool.length < count) {
    // If pool exhausted, reset used pool
    pool = getFilteredQuestions(options);
  }
  // Fisher-Yates shuffle
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, count);
}

